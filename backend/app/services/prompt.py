"""
Single source of truth for the AI assistant's system prompt and the per-tenant
business-profile context. Both the LINE webhook (webhooks.py) and the admin chat
sandbox (chat.py) import from here so behaviour never drifts between them.

The prompt is intentionally GENERIC (tenant-agnostic): all business-specific
details — services, prices, promotions, staff, FAQ, custom rules — are injected
at runtime via build_profile_context() from each tenant's own profile. Nothing
about any specific shop/clinic is hardcoded here.
"""
import os
import json
import logging

logger = logging.getLogger(__name__)

# Marker the AI appends when it decides to hand the conversation off to a human.
HANDOFF_MARKER = "[[HANDOFF]]"


def build_profile_context(p: dict) -> str:
    """
    Turn a tenant profile dict (from data/tenant_profile_{tenant_id}.json) into the
    text block that gets injected into the model context.
    """
    # Defensive .get() everywhere: the profile JSON is external/mutable (hand-edited,
    # partial AI extraction, upcoming Mongo migration) — a missing key must never 500
    # every chat/LINE message for the tenant.
    services_str = "\n".join([
        f"- {s.get('name', '')}: {s.get('price', '-')} บาท"
        for s in (p.get("services") or []) if isinstance(s, dict) and s.get("name")
    ])

    # Promotions
    promos = p.get("promotions", [])
    promos_str = ""
    if promos:
        promo_lines = []
        for promo in promos:
            line = f"- {promo.get('name', '')}: {promo.get('description', '')} (ส่วนลด {promo.get('discount', '-')}, ถึง {promo.get('valid_until') or 'ไม่ระบุ'})"
            if promo.get("conditions"):
                line += f" เงื่อนไข: {promo['conditions']}"
            promo_lines.append(line)
        promos_str = "\nโปรโมชันปัจจุบัน:\n" + "\n".join(promo_lines) + "\n"

    # Staff
    staff_list = p.get("staff", [])
    staff_str = ""
    if staff_list:
        staff_lines = [
            f"- {s.get('name', '')} ({s.get('role', '')}) — ความเชี่ยวชาญ: {', '.join(s.get('specialties') or [])} | ประสบการณ์ {s.get('experience', '-')}"
            for s in staff_list if isinstance(s, dict) and s.get("name")
        ]
        staff_str = "\nทีมงานและเจ้าหน้าที่:\n" + "\n".join(staff_lines) + "\n"

    # FAQ
    faq_list = p.get("faq", [])
    faq_str = ""
    if faq_list:
        faq_lines = [f"- ถาม: {f.get('question', '')}\n  ตอบ: {f.get('answer', '')}" for f in faq_list if isinstance(f, dict)]
        faq_str = "\nคำถามที่พบบ่อย (FAQ):\n" + "\n".join(faq_lines) + "\n"

    # Custom rules
    custom_rules = p.get("custom_rules", [])
    custom_rules_str = ""
    if custom_rules:
        rule_lines = [f"- หมวดหมู่ {cr.get('category', '-')}: {cr.get('rule', '-')}" for cr in custom_rules]
        custom_rules_str = "\nกฎนโยบาย/เงื่อนไขการเคลม/ประกันภัย/ข้อมูลการให้บริการเฉพาะเพิ่มเติม:\n" + "\n".join(rule_lines) + "\n"

    return (
        "กฎเกณฑ์และข้อมูลธุรกิจอย่างเป็นทางการของร้าน:\n"
        f"ชื่อร้าน: {p.get('company_name')}\n"
        f"เวลาทำการ: {p.get('business_hours')}\n"
        f"เบอร์ติดต่อ: {p.get('contact_number')}\n"
        f"บริการและราคาและระยะเวลา:\n{services_str}\n"
        f"{promos_str}{staff_str}{faq_str}{custom_rules_str}"
    )


def load_tenant_profile_context(tenant_id: str) -> str:
    """Read a tenant's profile JSON and return the profile context block (or '')."""
    profile_path = f"data/tenant_profile_{tenant_id}.json"
    if not os.path.exists(profile_path):
        return ""
    try:
        with open(profile_path, "r", encoding="utf-8") as f:
            p = json.load(f)
    except Exception as e:
        logger.error(f"Error loading tenant profile for {tenant_id}: {e}")
        return ""
    return build_profile_context(p)


