_CONTEXT_HEADER = (
    "ใช้เนื้อหาจากเอกสารความรู้ธุรกิจต่อไปนี้ในการตอบคำถามเป็นหลัก:\n"
    "====================\n"
    "{ctx}\n"
    "====================\n"
)


def build_system_prompt(mode: str, full_context: str) -> str:
    """
    Return the final system prompt. In CAG mode the full corpus is appended so the
    model sees the entire knowledge base; in RAG mode the dynamic chunks are passed
    separately via build_rag_context_message().
    """
    prompt = BASE_SYSTEM_PROMPT
    if mode == "cag":
        prompt += "\n\n" + _CONTEXT_HEADER.format(ctx=full_context)
    return prompt


def build_rag_context_message(full_context: str) -> dict:
    """System message carrying the retrieved RAG context, appended after history."""
    return {"role": "system", "content": _CONTEXT_HEADER.format(ctx=full_context)}
